// Tracks which variant index was last shown for each template, per browser session.
const variantIndex: Record<string, number> = {};

export function getNextAdVariant(templateId: string): string | undefined {
  const variants = AI_PREGENERATED_ADS[templateId];
  if (!variants || variants.length === 0) return undefined;
  const current = variantIndex[templateId] ?? -1;
  const next = (current + 1) % variants.length;
  variantIndex[templateId] = next;
  return variants[next];
}
